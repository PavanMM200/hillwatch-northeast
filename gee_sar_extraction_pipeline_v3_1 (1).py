import requests, rasterio, numpy as np
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

# ── GEE download → local GeoTIFF ─────────────────────────────────────────────
def download_geotiff(ee_image, bands, scale, out_path):
    """Download a clipped GEE image as a multi-band GeoTIFF (EPSG:4326)."""
    url = ee_image.select(bands).clip(aoi).toFloat().getDownloadURL({
        "scale": scale, "region": aoi, "format": "GEO_TIFF", "crs": "EPSG:4326"
    })
    r = requests.get(url, timeout=300)
    r.raise_for_status()
    with open(out_path, "wb") as f:
        f.write(r.content)

# ── Normalise a band to [0, 1] ───────────────────────────────────────────────
def normalize(band, lo, hi):
    return np.clip((band - lo) / (hi - lo), 0, 1)

# ── SAR → viewable RGB PNG ───────────────────────────────────────────────────
def sar_png(tif_path, png_path, title):
    """
    RGB composite: R = VV backscatter, G = VH backscatter, B = VV-VH ratio
    Typical dB ranges: VV [-25, 0], VH [-30, -5], diff [0, 15]
    """
    with rasterio.open(tif_path) as src:
        vv = src.read(1)
        vh = src.read(2)
    vv = np.nan_to_num(vv, nan=-30.0)
    vh = np.nan_to_num(vh, nan=-35.0)
    rgb = np.dstack([
        normalize(vv, -25,  0),
        normalize(vh, -30, -5),
        normalize(vv - vh, 0, 15)
    ])
    fig, ax = plt.subplots(figsize=(8, 8))
    ax.imshow(rgb)
    ax.set_title(title, fontsize=10)
    ax.axis("off")
    plt.tight_layout()
    plt.savefig(png_path, dpi=150, bbox_inches="tight")
    plt.close(fig)

# ── Sentinel-2 → true-colour PNG ─────────────────────────────────────────────
def s2_png(tif_path, png_path, title):
    """True-colour RGB from bands B4 (R), B3 (G), B2 (B) — surface reflectance."""
    with rasterio.open(tif_path) as src:
        r = src.read(1)
        g = src.read(2)
        b = src.read(3)
    rgb = np.dstack([normalize(np.nan_to_num(x), 0, 3000) for x in (r, g, b)]) ** 0.8
    fig, ax = plt.subplots(figsize=(8, 8))
    ax.imshow(rgb)
    ax.set_title(title, fontsize=10)
    ax.axis("off")
    plt.tight_layout()
    plt.savefig(png_path, dpi=150, bbox_inches="tight")
    plt.close(fig)

