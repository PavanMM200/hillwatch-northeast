"""## Cell 5 — Crisp 3D block renderer
High-DPI, colour-graded, hillshaded, with solid side-walls (the physical-model look).
"""

import numpy as np, rasterio, os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LightSource, Normalize
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401
from mpl_toolkits.mplot3d.art3d import Poly3DCollection

def _pix_m(transform, latc, stride=1):
    dx = abs(transform.a) * 111320.0 * np.cos(np.radians(latc)) * stride
    dy = abs(transform.e) * 110540.0 * stride
    return dx, dy

def _add_block_sides(ax, XX, YY, Ztop, base, color=(0.28, 0.24, 0.20)):
    H, W = Ztop.shape
    quads = []
    for j in range(W - 1):
        quads.append([(XX[0, j], YY[0, j], Ztop[0, j]), (XX[0, j + 1], YY[0, j + 1], Ztop[0, j + 1]), (XX[0, j + 1], YY[0, j + 1], base), (XX[0, j], YY[0, j], base)])
        quads.append([(XX[H - 1, j], YY[H - 1, j], Ztop[H - 1, j]), (XX[H - 1, j + 1], YY[H - 1, j + 1], Ztop[H - 1, j + 1]), (XX[H - 1, j + 1], YY[H - 1, j + 1], base), (XX[H - 1, j], YY[H - 1, j], base)])
    for i in range(H - 1):
        quads.append([(XX[i, 0], YY[i, 0], Ztop[i, 0]), (XX[i + 1, 0], YY[i + 1, 0], Ztop[i + 1, 0]), (XX[i + 1, 0], YY[i + 1, 0], base), (XX[i, 0], YY[i, 0], base)])
        quads.append([(XX[i, W - 1], YY[i, W - 1], Ztop[i, W - 1]), (XX[i + 1, W - 1], YY[i + 1, W - 1], Ztop[i + 1, W - 1]), (XX[i + 1, W - 1], YY[i + 1, W - 1], base), (XX[i, W - 1], YY[i, W - 1], base)])
    ax.add_collection3d(Poly3DCollection(quads, facecolor=color, edgecolor="none"))
    corners = [(XX[0, 0], YY[0, 0], base), (XX[0, W - 1], YY[0, W - 1], base), (XX[H - 1, W - 1], YY[H - 1, W - 1], base), (XX[H - 1, 0], YY[H - 1, 0], base)]
    ax.add_collection3d(Poly3DCollection([corners], facecolor=(0.15, 0.13, 0.11), edgecolor="none"))

def render_block(Z, dx_m, dy_m, title, out_png, cmap_name="turbo", ve=1.8, dpi=200, ax=None, block=True):
    Z = np.array(Z, dtype=float)
    if np.isnan(Z).any():
        try:
            from scipy import ndimage
            m = np.isnan(Z)
            if not m.all():
                idx = ndimage.distance_transform_edt(m, return_distances=False, return_indices=True)
                Z = Z[tuple(idx)]
            else:
                Z = np.nan_to_num(Z)
        except Exception:
            Z = np.nan_to_num(Z, nan=float(np.nanmin(Z)))
    H, W = Z.shape
    X = np.arange(W) * dx_m / 1000.0
    Y = np.arange(H) * dy_m / 1000.0
    XX, YY = np.meshgrid(X, Y)
    Zk = (Z - np.nanmin(Z)) / 1000.0 * ve
    cmap = plt.get_cmap(cmap_name)
    norm = Normalize(np.nanmin(Z), np.nanmax(Z))
    colors = cmap(norm(Z))
    ls = LightSource(azdeg=315, altdeg=45)
    colors[..., :3] = ls.shade_rgb(colors[..., :3], Z, vert_exag=ve * 6, blend_mode="soft")
    own = ax is None
    if own:
        fig = plt.figure(figsize=(11, 9)); ax = fig.add_subplot(111, projection="3d")
    ax.plot_surface(XX, YY, Zk, facecolors=colors, rstride=1, cstride=1, linewidth=0, antialiased=False, shade=False)
    base = float(Zk.min() - 0.06 * (Zk.max() - Zk.min() + 1e-6))
    if block:
        try:
            _add_block_sides(ax, XX, YY, Zk, base)
        except Exception as e:
            print("  sides skipped:", e)
    ax.set_title(title, fontsize=13, weight="bold", pad=12)
    ax.set_xlabel("E (km)"); ax.set_ylabel("N (km)")
    ax.view_init(elev=34, azim=-58)
    try:
        ax.set_box_aspect((max(X.max(), 1e-6), max(Y.max(), 1e-6), max(Zk.max() - base, 1e-6)))
    except Exception:
        pass
    ax.set_zticks([])
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm); sm.set_array(Z)
    if own:
        cb = fig.colorbar(sm, ax=ax, shrink=0.5, pad=0.02); cb.set_label("elevation (m)")
        plt.tight_layout(); plt.savefig(out_png, dpi=dpi, bbox_inches="tight", facecolor="white"); plt.close(fig)
        print("✅ saved", os.path.basename(out_png))

def render_file(tif, cmap, title, out_png):
    with rasterio.open(tif) as s:
        Z = s.read(1).astype(float); tr = s.transform
    dx, dy = _pix_m(tr, LAT)
    render_block(Z, dx, dy, title, out_png, cmap_name=cmap, ve=VERTICAL_EXAGGERATION)

render_file(f"{OUTPUT_DIR}/DSM_render.tif", "gist_earth", f"DSM — Surface — {LAT}, {LON}", f"{OUTPUT_DIR}/DSM_3D.png")
render_file(f"{OUTPUT_DIR}/DEM_render.tif", COLORMAP,     f"DEM — Elevation — {LAT}, {LON}", f"{OUTPUT_DIR}/DEM_3D.png")
render_file(f"{OUTPUT_DIR}/DTM_render.tif", "turbo",      f"DTM — Bare Earth — {LAT}, {LON}", f"{OUTPUT_DIR}/DTM_3D.png")

"""## Cell 6 — Interactive 3D (drag to rotate)"""

import plotly.graph_objects as go, rasterio, numpy as np

def plotly_surface(tif, out_html, title, colorscale="Turbo"):
    with rasterio.open(tif) as s:
        Z = s.read(1).astype(float)
    Z = np.where(np.isfinite(Z), Z, np.nan)
    fig = go.Figure(data=[go.Surface(z=Z, colorscale=colorscale, showscale=True,
        lighting=dict(ambient=0.5, diffuse=0.85, specular=0.25, roughness=0.5),
        contours={"z": {"show": True, "usecolormap": True, "project": {"z": True}}})])
    fig.update_layout(title=title, template="plotly_dark", width=1100, height=800,
        scene=dict(zaxis_title="elev (m)", aspectratio=dict(x=1, y=1, z=0.4)))
    fig.write_html(out_html, include_plotlyjs="cdn")
    print("✅ saved", os.path.basename(out_html))

plotly_surface(f"{OUTPUT_DIR}/DEM_render.tif", f"{OUTPUT_DIR}/DEM_3D_interactive.html", f"DEM 3D — {LAT}, {LON}")

