LAT, LON = float(_AOI["lat"]), float(_AOI["lon"])
g = _AOI["geojson"]["geometry"]
aoi = (ee.Geometry.Polygon(g["coordinates"]) if g["type"] == "Polygon"
       else ee.Geometry.MultiPolygon(g["coordinates"]))
OUT = "/content/terrain_out"; os.makedirs(OUT, exist_ok=True)
print(f"AOI  : {SITE_NAME}  {_AOI['area_km2']:.2f} km²")
