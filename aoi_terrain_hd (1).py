"""## Cell 5 — 📋 site.json — the node's static model features"""

import json

pt = ee.Geometry.Point([LON, LAT])
vals = stack.select(["elevation", "slope", "aspect"]).reduceRegion(
    ee.Reducer.first(), pt, 30).getInfo()
site = {
    "name": SITE_NAME, "lat": LAT, "lon": LON,
    "elevation": _r(vals.get("elevation")) if (_r := lambda v: None if v is None else round(float(v), 2)) else None,
    "slope": None if vals.get("slope") is None else round(float(vals["slope"]), 2),
    "aspect": None if vals.get("aspect") is None else round(float(vals["aspect"]), 2),
    "ndvi": None,
    "aoi_km2": round(float(_AOI["area_km2"]), 2),
    "aoi_bounds": {"sw_lat": _AOI["sw_lat"], "sw_lng": _AOI["sw_lng"],
                   "ne_lat": _AOI["ne_lat"], "ne_lng": _AOI["ne_lng"]},
    "dtm_source": DTM_LABEL,
}
if HAVE_NDVI:
    nv = ndvi.reduceRegion(ee.Reducer.first(), pt, 30).getInfo().get("NDVI")
    site["ndvi"] = None if nv is None else round(float(nv), 4)

# fall back to prototype_v3 config defaults so the vector is never incomplete
defaults = {"elevation": 350.0, "slope": 18.0, "aspect": 135.0, "ndvi": 0.55}
for k, v in defaults.items():
    if site.get(k) is None:
        site[k] = v
        print(f"   ⚠️ {k} unavailable at the node — using default {v}")

json.dump(site, open(f"{OUT}/site.json", "w"), indent=2)
print(json.dumps(site, indent=2))

"""## Cell 6 — 🧊 HD 3D renderer (no pixel thrown away)
Every DEM cell is drawn (`rstride=1, cstride=1`), shaded by a `LightSource`, saved at 220 dpi.
"""

import numpy as np, rasterio, os
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LightSource, Normalize
from mpl_toolkits.mplot3d import Axes3D  # noqa: F401
from mpl_toolkits.mplot3d.art3d import Poly3DCollection

VE = 1.8      #@param {type:"slider", min:1, max:5, step:0.1}
DPI = 220

def fill_nan(Z):
    Z = np.array(Z, dtype=float)
    Z[Z <= -9999] = np.nan
    if np.isnan(Z).any():
        try:
            from scipy import ndimage
            m = np.isnan(Z)
            if m.all(): return np.zeros_like(Z)
            idx = ndimage.distance_transform_edt(m, return_distances=False, return_indices=True)
            Z = Z[tuple(idx)]
        except Exception:
            Z = np.nan_to_num(Z, nan=float(np.nanmin(Z)))
    return Z

def px_m(tr, lat, s=1):
    return (abs(tr.a)*111320.0*np.cos(np.radians(lat))*s, abs(tr.e)*110540.0*s)

def sides(ax, XX, YY, Zt, base, col=(0.20,0.18,0.16)):
    H, W = Zt.shape; q = []
    for j in range(W-1):
        q.append([(XX[0,j],YY[0,j],Zt[0,j]),(XX[0,j+1],YY[0,j+1],Zt[0,j+1]),(XX[0,j+1],YY[0,j+1],base),(XX[0,j],YY[0,j],base)])
        q.append([(XX[H-1,j],YY[H-1,j],Zt[H-1,j]),(XX[H-1,j+1],YY[H-1,j+1],Zt[H-1,j+1]),(XX[H-1,j+1],YY[H-1,j+1],base),(XX[H-1,j],YY[H-1,j],base)])
    for i in range(H-1):
        q.append([(XX[i,0],YY[i,0],Zt[i,0]),(XX[i+1,0],YY[i+1,0],Zt[i+1,0]),(XX[i+1,0],YY[i+1,0],base),(XX[i,0],YY[i,0],base)])
        q.append([(XX[i,W-1],YY[i,W-1],Zt[i,W-1]),(XX[i+1,W-1],YY[i+1,W-1],Zt[i+1,W-1]),(XX[i+1,W-1],YY[i+1,W-1],base),(XX[i,W-1],YY[i,W-1],base)])
    ax.add_collection3d(Poly3DCollection(q, facecolor=col, edgecolor="none"))

def render(tif, cmap_name, title, out_png=None, ax=None):
    with rasterio.open(tif) as s:
        Z = fill_nan(s.read(1)); tr = s.transform
    dx, dy = px_m(tr, LAT)
    H, W = Z.shape
    XX, YY = np.meshgrid(np.arange(W)*dx/1000.0, np.arange(H)*dy/1000.0)
    Zk = (Z - Z.min())/1000.0*VE
    cmap = plt.get_cmap(cmap_name); norm = Normalize(Z.min(), Z.max())
    cols = cmap(norm(Z))
    cols[..., :3] = LightSource(315, 45).shade_rgb(cols[..., :3], Z, vert_exag=VE*6, blend_mode="soft")
    own = ax is None
    if own:
        fig = plt.figure(figsize=(12, 9)); ax = fig.add_subplot(111, projection="3d")
    ax.plot_surface(XX, YY, Zk, facecolors=cols, rstride=1, cstride=1,
                    linewidth=0, antialiased=False, shade=False)
    base = float(Zk.min() - 0.07*(Zk.max()-Zk.min()+1e-6))
    try: sides(ax, XX, YY, Zk, base)
    except Exception as e: print("  sides skipped:", e)
    ax.set_title(title, fontsize=13, weight="bold", pad=14)
    ax.set_xlabel("E (km)"); ax.set_ylabel("N (km)"); ax.set_zticks([])
    ax.view_init(elev=34, azim=-58)
    try: ax.set_box_aspect((max(XX.max(),1e-6), max(YY.max(),1e-6), max(Zk.max()-base,1e-6)))
    except Exception: pass
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm); sm.set_array(Z)
    if own:
        cb = fig.colorbar(sm, ax=ax, shrink=.55, pad=.02); cb.set_label("elevation (m)")
        plt.tight_layout(); plt.savefig(out_png, dpi=DPI, bbox_inches="tight", facecolor="white")
        plt.close(fig); print("✅", os.path.basename(out_png), f"({H}x{W} px grid)")

render(f"{OUT}/DSM_render.tif", "gist_earth", f"DSM · Surface · {SITE_NAME}", f"{OUT}/DSM_3D.png")
render(f"{OUT}/DEM_render.tif", "turbo",      f"DEM · Elevation · {SITE_NAME}", f"{OUT}/DEM_3D.png")
render(f"{OUT}/DTM_render.tif", "turbo",      f"DTM · Bare Earth · {SITE_NAME}", f"{OUT}/DTM_3D.png")

fig = plt.figure(figsize=(9, 17))
for k, (fn, cm, tt) in enumerate([("DSM_render.tif","gist_earth","DSM · Surface"),
                                  ("DEM_render.tif","turbo","DEM · Elevation"),
                                  ("DTM_render.tif","turbo","DTM · Bare Earth")], 1):
    render(f"{OUT}/{fn}", cm, tt, ax=fig.add_subplot(3, 1, k, projection="3d"))
plt.tight_layout(); plt.savefig(f"{OUT}/Combined_DEM_DTM_DSM.png", dpi=190,
                                bbox_inches="tight", facecolor="white"); plt.close(fig)
print("✅ Combined_DEM_DTM_DSM.png")

