def dl(img, bands, scale, path):
    url = img.select(bands).clip(aoi).toFloat().getDownloadURL(
        {"scale": scale, "region": aoi, "format": "GEO_TIFF", "crs": "EPSG:4326"})
    r = requests.get(url, timeout=600); r.raise_for_status()
    open(path, "wb").write(r.content)
    print(f"   ✓ {os.path.basename(path):26s} {len(r.content)/1e6:6.2f} MB")

